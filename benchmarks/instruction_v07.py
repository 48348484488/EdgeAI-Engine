#!/usr/bin/env python3
"""Three paired before/after SFT trials, fixed process-CPU training budget.

No test split is scored or used for checkpoint selection here. Validation NLL
selects among four checkpoints. All synthetic labels are generated by rules.
"""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import platform
import random
import sys
import time
import torch
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
from instruction_data import load_dataset,sha
from sft_model import expand_checkpoint,make_batch,response_loss,validation_loss
from transformer_model import export_transformer
CODE=('benchmarks/instruction_v07.py','tools/instruction_data.py','tools/sft_model.py','tools/transformer_model.py','tools/byte_bpe.py','tools/mixed_model.py','tools/hybrid_model.py','tools/train_tiny.py')

def save(path,obj):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    tmp=path.with_suffix('.tmp');tmp.write_text(json.dumps(obj,indent=2,ensure_ascii=False)+'\n');os.replace(tmp,path)

def identity(seed,cpu,threads,data_manifest,base):
    return dict(protocol='edge-sft-v07-1',seed=seed,cpu_budget=cpu,threads=threads,
                source_checkpoint_sha256=sha(base.read_bytes()),dataset_sha256=sha(data_manifest.read_bytes()),
                code={p:sha((ROOT/p).read_bytes()) for p in CODE},torch=str(torch.__version__),
                hyperparameters=dict(batch=16,lr=.001,weight_decay=.01,clip_norm=1,max_length=128,selection='minimum response validation NLL at 25/50/75/100 percent'),
                platform=platform.platform(),python=sys.version)

def cached_ok(row,key):
    if row.get('identity')!=key or len(row.get('artifacts',{}))!=4:return False
    for rel,digest in row['artifacts'].items():
        f=(ROOT/rel).resolve()
        if not f.is_relative_to(ROOT) or not f.is_file() or sha(f.read_bytes())!=digest:return False
    return True

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cpu-seconds',type=float,default=60);p.add_argument('--seeds',type=int,nargs='+',default=[11,22,33]);p.add_argument('--threads',type=int,default=1)
    p.add_argument('--data',type=Path,default=ROOT/'data/instructions_v07');p.add_argument('--out',type=Path,default=ROOT/'results/v07/training.json')
    p.add_argument('--model-dir',type=Path,default=ROOT/'models/instructions_v07');p.add_argument('--resume',action='store_true');a=p.parse_args()
    if not 0<a.cpu_seconds<=3600 or not 1<=a.threads<=64 or not a.seeds or len(set(a.seeds))!=len(a.seeds):p.error('invalid budget/threads/seeds')
    torch.set_num_threads(a.threads);torch.use_deterministic_algorithms(True)
    data,manifest=load_dataset(a.data);train=data['train'];valid=data['valid'];groups={}
    for row in train:groups.setdefault(row['task'],[]).append(row)
    a.model_dir.mkdir(parents=True,exist_ok=True)
    old={}
    if a.resume and a.out.exists():old={r['seed']:r for r in json.loads(a.out.read_text()).get('runs',[])}
    report=dict(protocol='paired identical expanded checkpoint before and after response-only SFT',cpu_budget_seconds=a.cpu_seconds,seeds=a.seeds,threads=a.threads,
                expected=len(a.seeds),dataset_sha256=sha((a.data/'manifest.json').read_bytes()),runs=[],
                accounting='training CPU includes batch creation, sampling, forward/backward, optimizer and batch hashing; initialization, validation, saving and inference excluded and reported separately',
                synthetic=True,energy_joules=None)
    invocation=time.perf_counter()
    for seed in a.seeds:
        base=ROOT/f'models/external_v06/bpe513-seed{seed}.pt'
        if not base.exists():raise FileNotFoundError('need v0.6 BPE checkpoint: '+str(base))
        key=identity(seed,a.cpu_seconds,a.threads,a.data/'manifest.json',base)
        if seed in old and cached_ok(old[seed],key):
            report['runs'].append(old[seed]);save(a.out,report);print(f'seed {seed}: verified cached trial',flush=True);continue
        trial=time.perf_counter();trial_cpu=time.process_time();init=time.perf_counter()
        cp=torch.load(base,map_location='cpu',weights_only=True);model,tok=expand_checkpoint(cp,seed)
        # Validate all example lengths before charging training, never truncate.
        for rows in (train,valid):
            for i in range(0,len(rows),16):make_batch(rows[i:i+16],tok)
        before=a.model_dir/f'seed{seed}-before.edge';after=a.model_dir/f'seed{seed}-after.edge'
        export_transformer(model,before,tokenizer=tok,max_generate=32)
        torch.save(dict(config=model.export_config(),state_dict=model.state_dict(),tokenizer=tok.payload(),seed=seed,phase='before',identity=key),before.with_suffix('.pt'))
        optimizer=torch.optim.AdamW(model.parameters(),lr=.001,weight_decay=.01)
        init_wall=time.perf_counter()-init;baseline_valid=validation_loss(model,valid,tok)
        rng=random.Random(7700+seed);tasks=sorted(groups);cpu=wall=0.;step=0;threshold=1
        best=float('inf');best_state=None;best_step=0;curve=[];seen={t:0 for t in tasks};digest=hashlib.sha256();validation_cpu=0.
        while cpu<a.cpu_seconds and step<100000:
            model.train();c=time.process_time();w=time.perf_counter()
            batch=[]
            for _ in range(16):
                task=rng.choice(tasks);row=rng.choice(groups[task]);batch.append(row);seen[task]+=1;digest.update(row['id'].encode())
            x,y=make_batch(batch,tok)
            optimizer.zero_grad(set_to_none=True);loss=response_loss(model(x),y)
            if not torch.isfinite(loss):raise RuntimeError('nonfinite training loss')
            loss.backward();torch.nn.utils.clip_grad_norm_(model.parameters(),1.);optimizer.step()
            cpu+=time.process_time()-c;wall+=time.perf_counter()-w;step+=1
            if cpu>=a.cpu_seconds*threshold/4 or cpu>=a.cpu_seconds:
                c=time.process_time();metric=validation_loss(model,valid,tok)
                curve.append(dict(step=step,train_cpu_seconds=cpu,validation_nll=metric))
                if metric<best:best=metric;best_state=copy.deepcopy(model.state_dict());best_step=step
                validation_cpu+=time.process_time()-c;threshold+=1
                print(json.dumps(dict(seed=seed,step=step,train_cpu_seconds=cpu,validation_nll=metric)),flush=True)
        if best_state is None:raise RuntimeError('no validation checkpoint')
        model.load_state_dict(best_state);model.eval();export_transformer(model,after,tokenizer=tok,max_generate=32)
        torch.save(dict(config=model.export_config(),state_dict=best_state,tokenizer=tok.payload(),seed=seed,phase='after',identity=key,selected_step=best_step),after.with_suffix('.pt'))
        artifacts={str(f.relative_to(ROOT)):sha(f.read_bytes()) for f in (before,before.with_suffix('.pt'),after,after.with_suffix('.pt'))}
        row=dict(seed=seed,identity=key,parameters=sum(p.numel() for p in model.parameters()),steps=step,selected_step=best_step,
                 train_cpu_seconds=cpu,train_wall_seconds=wall,initialization_wall_seconds=init_wall,validation_cpu_seconds=validation_cpu,
                 total_trial_wall_seconds=time.perf_counter()-trial,total_trial_cpu_seconds=time.process_time()-trial_cpu,
                 before_validation_nll=baseline_valid,selected_validation_nll=best,validation_curve=curve,examples_seen=seen,batch_ids_sha256=digest.hexdigest(),
                 before_path=str(before.relative_to(ROOT)),after_path=str(after.relative_to(ROOT)),file_bytes=after.stat().st_size,artifacts=artifacts)
        report['runs'].append(row);report['completed']=len(report['runs']);save(a.out,report)
    report['completed']=len(report['runs']);report['invocation_wall_seconds']=time.perf_counter()-invocation;save(a.out,report)
    print(json.dumps(dict(completed=report['completed'],out=str(a.out))),flush=True)
if __name__=='__main__':main()
